''' 
Python stores strings in continuous memory locations
We can access every single element of the string 

forward indexing starts from 0 and ends at n-1
backwards indexing starts from -1 

'''

s = "Python"

print(s[0])
print(s[1])
print(s[2])
print(s[3])
print(s[4])
print(s[5])


#space is also considered as character in python 

s = 'Rocky Rohith'
print(s[5])      #space is printed 

print(len(s))
print(s[len(s)-1])


#backward indexing

s = "Python"

print(s[-1])
print(s[-2])
print(s[-3])
print(s[-4])
print(s[-5])
print(s[-6])



